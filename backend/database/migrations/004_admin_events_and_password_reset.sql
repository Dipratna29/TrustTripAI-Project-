-- =====================================================================================
-- 004: Admin notification center (business events) + password reset + order columns
-- Run in the Supabase SQL editor. Safe to run more than once (idempotent).
--
-- Design
--   * admin_events is a shared admin inbox (one row per business event, one read state
--     for the whole admin team) - no per-user copies.
--   * Events are written by AFTER triggers in the SAME transaction as the business write,
--     so an event exists if and only if the order/registration/SOS/... was committed.
--   * dedup_key is UNIQUE and every insert uses ON CONFLICT DO NOTHING, so retries or
--     redelivery can never create a duplicate notification.
--   * metadata contains only an allowlist of non-sensitive fields (no phone numbers,
--     addresses, passwords, tokens or payment signatures).
--   * RLS: only the service role (backend) and active admins may read; travelers cannot.
-- =====================================================================================

-- ---------------------------------------------------------------------------
-- 0. Columns from migration 002 that are missing on some databases
--    (the COD order insert silently dropped address/phone without them)
