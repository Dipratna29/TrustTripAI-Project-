    ADD COLUMN IF NOT EXISTS payment_status VARCHAR(50) DEFAULT 'PENDING',
    ADD COLUMN IF NOT EXISTS payment_method VARCHAR(20) DEFAULT 'RAZORPAY',
    ADD COLUMN IF NOT EXISTS delivery_address TEXT,
    ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(30),
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();

-- ---------------------------------------------------------------------------
-- 1. Admin events table
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type    VARCHAR(60)  NOT NULL,
    category      VARCHAR(20)  NOT NULL,
    severity      VARCHAR(10)  NOT NULL DEFAULT 'INFO',
    title         TEXT         NOT NULL,
    message       TEXT         NOT NULL,
    entity_type   VARCHAR(30),
    entity_id     VARCHAR(64),
    actor_user_id BIGINT,
    metadata      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    dedup_key     VARCHAR(200) NOT NULL,
    read_at       TIMESTAMPTZ,
    read_by       TEXT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT admin_events_dedup_key_unique UNIQUE (dedup_key),
    CONSTRAINT admin_events_severity_check CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT admin_events_category_check CHECK (category IN
        ('ORDER', 'USER', 'INVENTORY', 'SOS', 'COMPLAINT', 'PAYMENT', 'GUIDE', 'OFFER', 'SYSTEM'))
);

CREATE INDEX IF NOT EXISTS idx_admin_events_created ON public.admin_events (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_admin_events_category ON public.admin_events (category, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_admin_events_unread ON public.admin_events (created_at DESC) WHERE read_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_admin_events_entity ON public.admin_events (entity_type, entity_id);

ALTER TABLE public.admin_events ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'admin_events' AND policyname = 'service_role_all_admin_events') THEN
        CREATE POLICY service_role_all_admin_events ON public.admin_events
            FOR ALL TO service_role USING (true) WITH CHECK (true);
    END IF;
    -- Active admins (Supabase Auth users linked in admin_users) may read for Realtime.
    -- Regular travelers never match this predicate.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated')
       AND EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'admin_users')
       AND NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'admin_events' AND policyname = 'active_admins_read_admin_events') THEN
        EXECUTE $p$
            CREATE POLICY active_admins_read_admin_events ON public.admin_events
                FOR SELECT TO authenticated
                USING (EXISTS (
                    SELECT 1 FROM public.admin_users a
                    WHERE a.user_id::text = auth.uid()::text AND upper(coalesce(a.status, 'ACTIVE')) = 'ACTIVE'
                ))
        $p$;
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 2. Helper: idempotent event insert (never raises into the business transaction
--    except for genuine programming errors)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.record_admin_event(
    p_event_type TEXT, p_category TEXT, p_severity TEXT, p_title TEXT, p_message TEXT,
    p_entity_type TEXT, p_entity_id TEXT, p_actor_user_id BIGINT, p_metadata JSONB, p_dedup_key TEXT
) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    new_id BIGINT;
BEGIN
    INSERT INTO public.admin_events
        (event_type, category, severity, title, message, entity_type, entity_id, actor_user_id, metadata, dedup_key)
    VALUES
        (p_event_type, p_category, p_severity, left(p_title, 200), left(p_message, 1000),
         p_entity_type, p_entity_id, p_actor_user_id, coalesce(p_metadata, '{}'::jsonb), p_dedup_key)
    ON CONFLICT (dedup_key) DO NOTHING
    RETURNING id INTO new_id;
    RETURN new_id;
END;
$$;

