-- 3f. SOS (critical). One event per incident row, regardless of how often the client retries.
CREATE OR REPLACE FUNCTION public.trg_admin_event_sos() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    PERFORM public.record_admin_event(
        'sos.triggered', 'SOS', 'CRITICAL',
        format('SOS #%s: %s', NEW.id, coalesce(NEW.emergency_type, 'Emergency')),
        format('@%s needs help%s.', coalesce(NEW.username, 'unknown'),
               CASE WHEN NEW.location_name IS NOT NULL THEN ' near ' || NEW.location_name ELSE '' END),
        'sos', NEW.id::text, NEW.user_id,
        jsonb_build_object('incident_id', NEW.id, 'emergency_type', NEW.emergency_type,
                           'status', NEW.status, 'username', NEW.username, 'has_location', NEW.latitude IS NOT NULL),
        'sos.triggered:' || NEW.id);
    RETURN NEW;
END $$;

