-- 3g. Payments (status is set server-side only after Razorpay signature + API verification)
CREATE OR REPLACE FUNCTION public.trg_admin_event_payment() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    st TEXT := upper(coalesce(NEW.status, ''));
BEGIN
    IF TG_OP = 'UPDATE' AND st IS NOT DISTINCT FROM upper(coalesce(OLD.status, '')) THEN
        RETURN NEW;
    END IF;
    IF st IN ('PAID', 'FAILED', 'REFUNDED') THEN
        PERFORM public.record_admin_event(
            'payment.' || lower(st), 'PAYMENT',
            CASE st WHEN 'FAILED' THEN 'WARNING' ELSE 'INFO' END,
            format('Payment %s: INR %s', lower(st), to_char(coalesce(NEW.amount_paise, 0) / 100.0, 'FM999999990.00')),
            format('Razorpay order %s%s.', NEW.razorpay_order_id,
                   CASE WHEN st = 'FAILED' AND NEW.failure_reason IS NOT NULL THEN ' - ' || left(NEW.failure_reason, 120) ELSE '' END),
            'payment', NEW.id::text, NEW.user_id,
            jsonb_build_object('payment_id', NEW.id, 'razorpay_order_id', NEW.razorpay_order_id, 'status', st,
                               'amount', coalesce(NEW.amount_paise, 0) / 100.0, 'currency', coalesce(NEW.currency, 'INR')),
            format('payment.%s:%s', lower(st), NEW.id));
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS admin_event_payment ON public.razorpay_payments;
CREATE TRIGGER admin_event_payment AFTER INSERT OR UPDATE OF status ON public.razorpay_payments
    FOR EACH ROW EXECUTE FUNCTION public.trg_admin_event_payment();

