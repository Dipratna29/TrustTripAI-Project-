-- 3i. Offers created / status changed
CREATE OR REPLACE FUNCTION public.trg_admin_event_offer() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM public.record_admin_event(
            'offer.created', 'OFFER', 'INFO', format('Offer created: %s', NEW.title),
            format('Status %s, valid %s to %s.', NEW.status, coalesce(NEW.start_date::text, '-'), coalesce(NEW.end_date::text, '-')),
            'offer', NEW.id::text, NULL,
            jsonb_build_object('offer_id', NEW.id, 'title', NEW.title, 'status', NEW.status),
            'offer.created:' || NEW.id);
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        PERFORM public.record_admin_event(
            'offer.status_changed', 'OFFER', 'INFO', format('Offer %s: %s', lower(coalesce(NEW.status, '')), NEW.title),
            format('Status changed from %s to %s.', OLD.status, NEW.status),
            'offer', NEW.id::text, NULL,
            jsonb_build_object('offer_id', NEW.id, 'title', NEW.title, 'from', OLD.status, 'to', NEW.status),
            format('offer.status:%s:%s', NEW.id, to_char(clock_timestamp(), 'YYYYMMDDHH24MISSUS')));
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS admin_event_offer ON public.offers;
CREATE TRIGGER admin_event_offer AFTER INSERT OR UPDATE OF status ON public.offers
    FOR EACH ROW EXECUTE FUNCTION public.trg_admin_event_offer();

-- ---------------------------------------------------------------------------
-- 4. Password reset codes (custom auth: users.password is a Werkzeug hash)
--    Only a SHA-256 hash of the 6-digit code is stored.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.password_reset_codes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL,
    code_hash    VARCHAR(128) NOT NULL,
    expires_at   TIMESTAMPTZ NOT NULL,
    attempts     INT NOT NULL DEFAULT 0,
    consumed_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_password_reset_user ON public.password_reset_codes (user_id, created_at DESC);
ALTER TABLE public.password_reset_codes ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'password_reset_codes' AND policyname = 'service_role_all_password_reset') THEN
        CREATE POLICY service_role_all_password_reset ON public.password_reset_codes
            FOR ALL TO service_role USING (true) WITH CHECK (true);
    END IF;
END $$;

