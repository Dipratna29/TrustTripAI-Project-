-- 3a. New user registered
CREATE OR REPLACE FUNCTION public.trg_admin_event_user_registered() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    PERFORM public.record_admin_event(
        'user.registered', 'USER', 'INFO',
        'New traveler registered',
        format('@%s (%s) created an account.', NEW.username, coalesce(NEW.name, NEW.username)),
        'user', NEW.user_id::text, NEW.user_id,
        jsonb_build_object('username', NEW.username, 'created_at', NEW.created_at),
        'user.registered:' || NEW.user_id);
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS admin_event_user_registered ON public.users;
CREATE TRIGGER admin_event_user_registered AFTER INSERT ON public.users
    FOR EACH ROW EXECUTE FUNCTION public.trg_admin_event_user_registered();

-- 3b. Orders: placed + status changed
CREATE OR REPLACE FUNCTION public.trg_admin_event_order() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    item_name TEXT;
    method TEXT;
BEGIN
    SELECT name INTO item_name FROM public.inventory_items WHERE id = NEW.equipment_id;
    item_name := coalesce(item_name, 'Equipment #' || NEW.equipment_id);
    method := upper(coalesce(NEW.payment_method, 'RAZORPAY'));

    IF TG_OP = 'INSERT' THEN
        PERFORM public.record_admin_event(
            'order.placed', 'ORDER', 'INFO',
            format('New order #%s', NEW.id),
            format('%s x %s - INR %s (%s)', NEW.quantity, item_name,
                   to_char(NEW.total_price, 'FM999999990.00'),
                   CASE WHEN method = 'COD' THEN 'Cash on Delivery' ELSE 'Paid online' END),
            'order', NEW.id::text, NEW.user_id,
            jsonb_build_object('order_id', NEW.id, 'status', NEW.status, 'quantity', NEW.quantity,
                               'item', item_name, 'equipment_id', NEW.equipment_id,
                               'total', NEW.total_price, 'currency', 'INR', 'payment_method', method),
            'order.placed:' || NEW.id);
    ELSIF TG_OP = 'UPDATE' AND NEW.status IS DISTINCT FROM OLD.status THEN
        PERFORM public.record_admin_event(
            'order.status_changed', 'ORDER',
            CASE WHEN lower(coalesce(NEW.status, '')) LIKE 'cancel%' OR lower(coalesce(NEW.status, '')) LIKE 'refund%'
                 THEN 'WARNING' ELSE 'INFO' END,
            format('Order #%s is now %s', NEW.id, NEW.status),
            format('Status changed from %s to %s (%s x %s).', coalesce(OLD.status, '-'), NEW.status, NEW.quantity, item_name),
            'order', NEW.id::text, NEW.user_id,
            jsonb_build_object('order_id', NEW.id, 'from', OLD.status, 'to', NEW.status,
                               'total', NEW.total_price, 'currency', 'INR'),
            format('order.status:%s:%s>%s:%s', NEW.id, coalesce(OLD.status, ''), NEW.status,
                   to_char(clock_timestamp(), 'YYYYMMDDHH24MISSUS')));
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS admin_event_order ON public.equipment_orders;
CREATE TRIGGER admin_event_order AFTER INSERT OR UPDATE OF status ON public.equipment_orders
    FOR EACH ROW EXECUTE FUNCTION public.trg_admin_event_order();

-- 3c. Inventory: low stock / out of stock (only when crossing the threshold, so the
--     same ongoing condition is not re-alerted) and back-in-stock
CREATE OR REPLACE FUNCTION public.trg_admin_event_inventory() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    min_stock INT := coalesce(NEW.minimum_stock, 5);
    stamp TEXT := to_char(clock_timestamp(), 'YYYYMMDDHH24MISSUS');
BEGIN
    IF NEW.current_stock IS NOT DISTINCT FROM OLD.current_stock THEN
        RETURN NEW;
    END IF;

    IF NEW.current_stock <= 0 AND OLD.current_stock > 0 THEN
        PERFORM public.record_admin_event(
            'inventory.out_of_stock', 'INVENTORY', 'CRITICAL',
            format('%s is out of stock', NEW.name),
            format('Stock fell from %s to 0. Travelers can no longer order this item.', OLD.current_stock),
            'inventory_item', NEW.id::text, NULL,
            jsonb_build_object('item_id', NEW.id, 'item', NEW.name, 'previous_stock', OLD.current_stock,
                               'current_stock', NEW.current_stock, 'minimum_stock', min_stock),
            format('inventory.out:%s:%s', NEW.id, stamp));
    ELSIF NEW.current_stock <= min_stock AND OLD.current_stock > min_stock THEN
        PERFORM public.record_admin_event(
            'inventory.low_stock', 'INVENTORY', 'WARNING',
            format('Low stock: %s', NEW.name),
            format('Stock fell from %s to %s (minimum %s).', OLD.current_stock, NEW.current_stock, min_stock),
            'inventory_item', NEW.id::text, NULL,
            jsonb_build_object('item_id', NEW.id, 'item', NEW.name, 'previous_stock', OLD.current_stock,
                               'current_stock', NEW.current_stock, 'minimum_stock', min_stock),
            format('inventory.low:%s:%s', NEW.id, stamp));
    ELSIF NEW.current_stock > min_stock AND OLD.current_stock <= min_stock THEN
        PERFORM public.record_admin_event(
            'inventory.restocked', 'INVENTORY', 'INFO',
            format('%s restocked', NEW.name),
            format('Stock rose from %s to %s.', OLD.current_stock, NEW.current_stock),
            'inventory_item', NEW.id::text, NULL,
            jsonb_build_object('item_id', NEW.id, 'item', NEW.name, 'previous_stock', OLD.current_stock,
                               'current_stock', NEW.current_stock, 'minimum_stock', min_stock),
            format('inventory.restock:%s:%s', NEW.id, stamp));
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS admin_event_inventory ON public.inventory_items;
CREATE TRIGGER admin_event_inventory AFTER UPDATE OF current_stock ON public.inventory_items
    FOR EACH ROW EXECUTE FUNCTION public.trg_admin_event_inventory();

-- 3d. Manual stock-in / stock-out adjustments (admin inventory transactions)
CREATE OR REPLACE FUNCTION public.trg_admin_event_inventory_tx() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    item_name TEXT;
BEGIN
    IF upper(coalesce(NEW.type, '')) = 'ORDER_DEDUCT' THEN
        RETURN NEW; -- covered by the order event
    END IF;
    SELECT name INTO item_name FROM public.inventory_items WHERE id = NEW.item_id;
    PERFORM public.record_admin_event(
        'inventory.adjusted', 'INVENTORY', 'INFO',
        format('Stock %s: %s', CASE WHEN coalesce(NEW.new_stock, 0) >= coalesce(NEW.previous_stock, 0) THEN 'in' ELSE 'out' END,
               coalesce(item_name, 'Item #' || NEW.item_id)),
        format('%s units (%s -> %s). %s', NEW.quantity, NEW.previous_stock, NEW.new_stock, coalesce(NEW.reason, '')),
        'inventory_item', NEW.item_id::text, NULL,
        jsonb_build_object('item_id', NEW.item_id, 'item', item_name, 'type', NEW.type, 'quantity', NEW.quantity,
                           'previous_stock', NEW.previous_stock, 'new_stock', NEW.new_stock, 'transaction_id', NEW.id),
        'inventory.tx:' || NEW.id);
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS admin_event_inventory_tx ON public.inventory_transactions;
CREATE TRIGGER admin_event_inventory_tx AFTER INSERT ON public.inventory_transactions
    FOR EACH ROW EXECUTE FUNCTION public.trg_admin_event_inventory_tx();

